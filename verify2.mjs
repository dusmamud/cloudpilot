import { chromium } from '/home/hatch/.npm-global/lib/node_modules/playwright/index.mjs'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
const errs = []
page.on('pageerror', e => errs.push(String(e)))
await page.goto('http://127.0.0.1:4177/pricing.html', { waitUntil: 'networkidle' })
console.log('pricing url:', page.url(), 'has Monthly:', (await page.textContent('body')).includes('Monthly'))
await page.getByRole('button', { name: 'Monthly' }).click()
await page.waitForTimeout(400)
console.log('pricing monthly $19:', (await page.textContent('body')).includes('$19'))
await page.goto('http://127.0.0.1:4177/login.html', { waitUntil: 'networkidle' })
await page.getByRole('button', { name: 'Fill demo account' }).click()
await page.getByRole('button', { name: 'Sign in', exact: true }).click()
await page.waitForTimeout(400)
console.log('login demo ok:', (await page.textContent('body')).includes('Signed in (demo)'))
await page.goto('http://127.0.0.1:4177/help.html', { waitUntil: 'networkidle' })
await page.getByPlaceholder('Search help articles').fill('SSO')
await page.waitForTimeout(300)
console.log('help SSO:', (await page.textContent('body')).includes('Set up SSO'))
await page.goto('http://127.0.0.1:4177/roi-calculator.html', { waitUntil: 'networkidle' })
console.log('roi saved:', (await page.textContent('body')).includes('Saved per year'))
await page.goto('http://127.0.0.1:4177/request-demo.html', { waitUntil: 'networkidle' })
await page.getByLabel('Full name').fill('Test User')
await page.getByLabel('Work email').fill('test@acme.com')
await page.getByRole('button', { name: 'Start Free Trial' }).click()
await page.waitForTimeout(400)
console.log('trial form ok:', (await page.textContent('body')).includes('on its way'))
console.log('pageerrors:', errs)
await browser.close()
